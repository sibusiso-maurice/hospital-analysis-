SELECT
  *
FROM
  "BRIGHTHOSPITAL"."PUBLIC"."PATIENTSDATA"
LIMIT
  10;

---Age Distribution
  SELECT
  AGE,
  COUNT(*) AS total_patients,
  SUM(CASE WHEN READMISSION = 1 THEN 1 ELSE 0 END) AS readmissions,
  ROUND(100.0 * SUM(CASE WHEN READMISSION = 1 THEN 1 ELSE 0 END)/COUNT(*), 2) AS readmission_rate
FROM "BRIGHTHOSPITAL"."PUBLIC"."PATIENTSDATA"
GROUP BY AGE
ORDER BY AGE;

---Gender Distribution
SELECT
  GENDER,
  COUNT(*) AS total_patients,
  SUM(CASE WHEN READMISSION = 1 THEN 1 ELSE 0 END) AS readmissions,
  ROUND(100.0 * SUM(CASE WHEN READMISSION = 1 THEN 1 ELSE 0 END)/COUNT(*), 2) AS readmission_rate
FROM "BRIGHTHOSPITAL"."PUBLIC"."PATIENTSDATA"
GROUP BY GENDER;

---Readmission by Number of Diagnoses
SELECT
  NUMBER_OF_DIAGNOSES,
  COUNT(*) AS total_patients,
  SUM(CASE WHEN READMISSION = 1 THEN 1 ELSE 0 END) AS readmissions,
  ROUND(100.0 * SUM(CASE WHEN READMISSION = 1 THEN 1 ELSE 0 END)/COUNT(*), 2) AS readmission_rate
FROM "BRIGHTHOSPITAL"."PUBLIC"."PATIENTSDATA"
GROUP BY NUMBER_OF_DIAGNOSES
ORDER BY NUMBER_OF_DIAGNOSES;

---Readmission by Admission Type (Elective vs Emergency)
SELECT
  ADMISSION_TYPE,
  COUNT(*) AS total_patients,
  SUM(CASE WHEN READMISSION = 1 THEN 1 ELSE 0 END) AS readmissions,
  ROUND(100.0 * SUM(CASE WHEN READMISSION = 1 THEN 1 ELSE 0 END)/COUNT(*), 2) AS readmission_rate
FROM "BRIGHTHOSPITAL"."PUBLIC"."PATIENTSDATA"
GROUP BY ADMISSION_TYPE;

---Readmission by Length of Stay (LOS)
SELECT
  CASE 
    WHEN LENGTH_OF_STAY <= 2 THEN '0-2 days'
    WHEN LENGTH_OF_STAY BETWEEN 3 AND 5 THEN '3-5 days'
    WHEN LENGTH_OF_STAY BETWEEN 6 AND 10 THEN '6-10 days'
    ELSE '11+ days'
  END AS LOS_Category,
  COUNT(*) AS total_patients,
  SUM(CASE WHEN READMISSION = 1 THEN 1 ELSE 0 END) AS readmissions,
  ROUND(100.0 * SUM(CASE WHEN READMISSION = 1 THEN 1 ELSE 0 END)/COUNT(*), 2) AS readmission_rate
FROM "BRIGHTHOSPITAL"."PUBLIC"."PATIENTSDATA"
GROUP BY LOS_Category
ORDER BY LOS_Category;
